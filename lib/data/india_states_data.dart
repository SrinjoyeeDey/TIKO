  static IndiaStateData? getState(String id) => states[id];

  static String? getNextStateId(String currentId) {
    final idx = stateOrder.indexOf(currentId);
    if (idx < 0 || idx >= stateOrder.length - 1) return null;
    return stateOrder[idx + 1];
  }

  static String? getPreviousStateId(String currentId) {
    final idx = stateOrder.indexOf(currentId);
    if (idx <= 0) return null;
    return stateOrder[idx - 1];
  }
